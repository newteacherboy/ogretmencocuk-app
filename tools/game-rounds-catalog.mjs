/* Generate a private server catalog; retain the original five-key legacy catalog. */
import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({});
vm.runInContext(fs.readFileSync('curriculum.js','utf8')+';globalThis.gameCatalog=games;',context);
const rows=context.gameCatalog.flatMap(g=>g.questions.map((q,id)=>({activity_id:g.id,id,payload:{...q,id,answer:q.ordering?q.answerOrder:q.answer,answer_kind:q.ordering?'order':'choice'}})));
const quote=s=>"'"+s.replaceAll("'","''")+"'";
const sql='-- Generated by node tools/game-rounds-catalog.mjs\ninsert into turkce_private.game_question_bank(activity_id,question_id,payload) values\n'+rows.map(r=>`(${quote(r.activity_id)},${r.id},${quote(JSON.stringify(r.payload))}::jsonb)`).join(',\n')+'\non conflict(activity_id,question_id) do update set payload=excluded.payload;\n';
fs.writeFileSync('supabase/member-release/game-rounds-catalog.sql',sql);
console.log(`${rows.length} questions in ${context.gameCatalog.length} game pools`);
